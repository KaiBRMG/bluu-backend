/**
 * GoLogin management — creating, editing and deleting profiles; creating,
 * deleting and filling folders; and sharing both with members.
 *
 * Everything here speaks as the **master** workspace (`getMasterGoLoginClient`),
 * the same identity the Members surface already uses. A non-admin with the right
 * capability administers the workspace *server-side*; they never hold the master
 * token (see gologin.md § Admins use the master token).
 *
 * ## The fingerprint is the thing being protected
 *
 * A GoLogin profile is a disguise for a live, logged-in social account, and the
 * disguise is only as good as its consistency. GoLogin's own guidance is that OS,
 * user agent, resolution, fonts, canvas, WebGL and CPU/RAM must **never change
 * after an account has logged in**. Three decisions here follow from that:
 *
 *   1. **Create is `POST /browser/quick`** — GoLogin's "profile on the default
 *      settings" — so the fingerprint is generated by GoLogin, consistently, for
 *      the chosen OS. Nothing here assembles one by hand.
 *   2. **No edit ever calls `PUT /browser/{id}/custom`**, which re-randomises
 *      every parameter the body omits. Name, proxy and folders each go through an
 *      endpoint that touches only that field; notes go through the SDK's own
 *      read-whole-document-write-it-back update.
 *   3. **A profile never exists without the proxy it was created for.** If
 *      attaching the proxy fails, the new profile is deleted rather than left on
 *      the operator's real IP for someone to launch.
 *
 * ## The request budget
 *
 * Every call here is a provider request, and a 429 revokes the master token for
 * good (rule 9e). Everything is sequential, bounded by the batch caps in the
 * routes, and reads come from the 60s memos in `gologinAccountService`.
 * Membership writes patch that memo in place (`applyFolderMembership`) rather
 * than dropping it — only structural changes (a folder created or deleted, a
 * profile created or deleted) force the next `GET /user`.
 */
